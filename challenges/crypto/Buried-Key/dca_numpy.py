def g2(x):
    return ((x << 1) ^ 0x1b) & 0xff if x & 0x80 else (x << 1) & 0xff
g2_vec = np.vectorize(g2)

def g3(x):
    return g2(x) ^ x
g3_vec = np.vectorize(g3)

def dca_numpy(table_data):
    entries = np.frombuffer(table_data, dtype=np.uint32)
    # entries is (256,)
    
    # Precompute bits of entries
    # entries_bits is (4, 8, 256)
    entries_bits = np.zeros((4, 8, 256), dtype=np.int8)
    for b in range(4):
        byte_vals = (entries >> (b * 8)) & 0xff
        for bit in range(8):
            entries_bits[b, bit] = (byte_vals >> bit) & 1
            
    # Center bits around 0 (-0.5, 0.5) to use correlation
    entries_bits = entries_bits.astype(np.float32) - 0.5
    
    # Precompute bits of S-box and its variations
    # sbox_bits is (3, 256, 8)
    sbox_variations = np.zeros((3, 256), dtype=np.uint8)
    sbox_variations[0] = sbox
    sbox_variations[1] = g2_vec(sbox)
    sbox_variations[2] = g3_vec(sbox)
    
    sbox_bits = np.zeros((3, 256, 8), dtype=np.float32)
    for v in range(3):
        for bit in range(8):
            sbox_bits[v, :, bit] = ((sbox_variations[v] >> bit) & 1).astype(np.float32) - 0.5
            
    best_keys = []
    
    for i in range(16): # This is for a single table, but wait, the input is for a single table
        pass
    
    # Actually, the function should process one table at a time
    # table_data is 1024 bytes (one table)
    
    max_corr_all_k = np.zeros(256)
    
    for k in range(256):
        # x ^ k
        idx = np.bitwise_xor(np.arange(256, dtype=np.uint8), k)
        # s_bits for this k: (3, 256, 8)
        s_bits_k = sbox_bits[:, idx, :]
        
        # Now compute correlation between entries_bits (4, 8, 256) and s_bits_k (3, 256, 8)
        # We want max over (4, 8, 3, 8) bit pairs
        # We can use matrix multiplication!
        # entries_bits_flat: (32, 256)
        # s_bits_k_flat: (24, 256)
        # corr: (32, 24)
        e_flat = entries_bits.reshape(32, 256)
        s_flat = s_bits_k.reshape(24, 256)
        
        corr_matrix = np.abs(np.dot(e_flat, s_flat.T)) # (32, 24)
        max_corr_all_k[k] = np.max(corr_matrix)
        
    best_k = np.argmax(max_corr_all_k)
    return best_k, max_corr_all_k[best_k]

